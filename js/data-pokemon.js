// 進化チェーンの全経路を返す（分岐あり対応）
// 各経路は [{type:"mon",id,name} | {type:"cond",cond}] の配列
export function getEvoPaths(dexId) {
  // ルートまで遡る
  let root = dexId;
  const visited = new Set();
  while (EVOLUTION_DATA[root] && EVOLUTION_DATA[root].pre && EVOLUTION_DATA[root].pre.length > 0) {
    if (visited.has(root)) break;
    visited.add(root);
    root = EVOLUTION_DATA[root].pre[0].id;
  }
  // ルートから全経路をDFSで列挙
  function dfs(id) {
    const name = POKEMON_DATA[id - 1][1];
    const e = EVOLUTION_DATA[id];
    const nexts = (e && e.next) || [];
    if (nexts.length === 0) return [[{ type: "mon", id, name }]];
    const paths = [];
    for (const n of nexts) {
      for (const sub of dfs(n.id)) {
        paths.push([{ type: "mon", id, name }, { type: "cond", cond: n.cond }, ...sub]);
      }
    }
    return paths;
  }
  return dfs(root);
}

